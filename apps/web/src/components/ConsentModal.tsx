import React, { useEffect, useState } from 'react'
import { Card, CardContent } from './ui/Card'
import { Button } from './ui/Button'
import { Shield, ExternalLink } from 'lucide-react'

export function ConsentModal() {
  const [show, setShow] = useState(false)

  useEffect(() => {
    const hasConsented = localStorage.getItem('paipersum_consent')
    if (!hasConsented) {
      setShow(true)
    }
  }, [])

  const handleAccept = () => {
    localStorage.setItem('paipersum_consent', 'true')
    setShow(false)
  }

  if (!show) return null

  return (
    <div className="fixed inset-0 bg-black/50 z-50 flex items-center justify-center p-4">
      <Card className="w-full max-w-lg">
        <CardContent className="p-6">
          <div className="flex items-start gap-4">
            <div className="flex-shrink-0">
              <div className="w-10 h-10 rounded-lg bg-brand-yellow flex items-center justify-center">
                <Shield className="h-6 w-6 text-white" />
              </div>
            </div>
            <div className="flex-1">
              <h3 className="text-lg font-semibold text-ink-900 mb-2">
                Important Legal Notice
              </h3>
              <div className="space-y-3 text-sm text-ink-600">
                <p>
                  PaiperSum provides AI-powered analysis of legal documents for informational purposes only. 
                  <strong className="text-ink-900"> This is not legal advice.</strong>
                </p>
                <p>
                  By using this service, you understand that:
                </p>
                <ul className="list-disc list-inside space-y-1 ml-4">
                  <li>Results are generated by artificial intelligence and may contain errors</li>
                  <li>You should consult with a qualified attorney for legal decisions</li>
                  <li>PaiperSum is not a law firm and does not provide legal services</li>
                  <li>Your documents are processed securely and not stored permanently</li>
                </ul>
                <p>
                  Please review our{' '}
                  <a 
                    href="/terms" 
                    className="text-brand-blue hover:underline inline-flex items-center gap-1"
                    target="_blank"
                    rel="noopener noreferrer"
                  >
                    Terms of Service
                    <ExternalLink className="h-3 w-3" />
                  </a>
                  {' '}and{' '}
                  <a 
                    href="/privacy" 
                    className="text-brand-blue hover:underline inline-flex items-center gap-1"
                    target="_blank"
                    rel="noopener noreferrer"
                  >
                    Privacy Policy
                    <ExternalLink className="h-3 w-3" />
                  </a>
                  {' '}for complete details.
                </p>
              </div>
              <div className="flex gap-3 mt-6">
                <Button onClick={handleAccept} className="flex-1">
                  I Understand and Accept
                </Button>
                <Button 
                  variant="secondary" 
                  onClick={() => window.location.href = 'https://google.com'}
                  className="flex-1"
                >
                  Decline and Leave
                </Button>
              </div>
            </div>
          </div>
        </CardContent>
      </Card>
    </div>
  )
}