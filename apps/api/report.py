from fpdf import FPDF
from typing import Dict, Any, List
import os
from datetime import datetime

class PaiperSumPDF(FPDF):
    def __init__(self):
        super().__init__()
        self.set_auto_page_break(auto=True, margin=15)
        self.add_page()
    
    def header(self):
        # Logo and title
        self.set_font('Arial', 'B', 16)
        self.set_text_color(15, 76, 129)  # Brand blue
        self.cell(0, 10, 'PaiperSum Legal Analysis Report', 0, 1, 'C')
        self.ln(5)
    
    def footer(self):
        self.set_y(-15)
        self.set_font('Arial', 'I', 8)
        self.set_text_color(128, 128, 128)
        self.cell(0, 10, f'Generated on {datetime.now().strftime("%Y-%m-%d %H:%M:%S")} | Not legal advice', 0, 0, 'C')
    
    def add_risk_section(self, risk_score: int, confidence: float):
        """Add risk assessment section"""
        self.set_font('Arial', 'B', 14)
        self.set_text_color(0, 0, 0)
        self.cell(0, 10, 'Risk Assessment', 0, 1)
        self.ln(2)
        
        # Risk score
        self.set_font('Arial', '', 12)
        self.cell(0, 8, f'Overall Risk Score: {risk_score}%', 0, 1)
        
        # Risk level
        if risk_score >= 75:
            risk_level = "HIGH RISK"
            color = (198, 40, 40)  # Red
        elif risk_score >= 50:
            risk_level = "MODERATE RISK"
            color = (249, 168, 37)  # Yellow
        elif risk_score >= 25:
            risk_level = "LOW RISK"
            color = (46, 125, 50)  # Green
        else:
            risk_level = "MINIMAL RISK"
            color = (46, 125, 50)  # Green
        
        self.set_text_color(*color)
        self.set_font('Arial', 'B', 12)
        self.cell(0, 8, f'Risk Level: {risk_level}', 0, 1)
        
        # Confidence
        self.set_text_color(0, 0, 0)
        self.set_font('Arial', '', 12)
        self.cell(0, 8, f'Confidence: {confidence:.1%}', 0, 1)
        self.ln(5)
    
    def add_clauses_section(self, clauses: List[Dict[str, Any]]):
        """Add legal clauses section"""
        if not clauses:
            self.set_font('Arial', 'I', 12)
            self.set_text_color(128, 128, 128)
            self.cell(0, 8, 'No significant legal clauses identified.', 0, 1)
            return
        
        self.set_font('Arial', 'B', 14)
        self.set_text_color(0, 0, 0)
        self.cell(0, 10, 'Identified Legal Clauses', 0, 1)
        self.ln(2)
        
        for i, clause in enumerate(clauses, 1):
            # Clause title with risk indicator
            self.set_font('Arial', 'B', 12)
            risk_color = {
                'red': (198, 40, 40),
                'yellow': (249, 168, 37),
                'green': (46, 125, 50)
            }.get(clause.get('risk', 'green'), (0, 0, 0))
            
            self.set_text_color(*risk_color)
            risk_indicator = "●" if clause.get('risk') == 'red' else "○" if clause.get('risk') == 'yellow' else "○"
            self.cell(0, 8, f'{i}. {risk_indicator} {clause.get("title", "Unknown Clause")}', 0, 1)
            
            # Clause summary
            self.set_text_color(0, 0, 0)
            self.set_font('Arial', '', 11)
            summary = clause.get('summary', 'No summary available.')
            self.multi_cell(0, 6, summary)
            
            # Citation
            citation = clause.get('citation', '')
            if citation:
                self.set_font('Arial', 'I', 10)
                self.set_text_color(100, 100, 100)
                self.cell(0, 5, 'Source:', 0, 1)
                self.multi_cell(0, 5, f'"{citation[:200]}{"..." if len(citation) > 200 else ""}"')
            
            self.ln(3)
    
    def add_disclaimer(self):
        """Add legal disclaimer"""
        self.ln(10)
        self.set_font('Arial', 'B', 12)
        self.set_text_color(198, 40, 40)  # Red
        self.cell(0, 8, 'IMPORTANT LEGAL DISCLAIMER', 0, 1)
        
        self.set_font('Arial', '', 10)
        self.set_text_color(0, 0, 0)
        disclaimer_text = (
            "This analysis is generated by artificial intelligence and is for informational purposes only. "
            "It does not constitute legal advice, and you should consult with a qualified attorney for any legal decisions. "
            "PaiperSum is not a law firm and does not provide legal services. The accuracy of this analysis cannot be guaranteed, "
            "and you should not rely on it as the sole basis for legal decisions."
        )
        self.multi_cell(0, 5, disclaimer_text)

def generate_pdf_report(analysis_data: Dict[str, Any]) -> bytes:
    """Generate PDF report from analysis data"""
    try:
        pdf = PaiperSumPDF()
        
        # Add risk assessment
        pdf.add_risk_section(
            analysis_data.get('risk_score', 0),
            analysis_data.get('confidence', 0.0)
        )
        
        # Add clauses
        pdf.add_clauses_section(analysis_data.get('clauses', []))
        
        # Add disclaimer
        pdf.add_disclaimer()
        
        return pdf.output(dest='S').encode('latin1')
    
    except Exception as e:
        # Fallback to simple text report
        return generate_text_report(analysis_data).encode('utf-8')

def generate_text_report(analysis_data: Dict[str, Any]) -> str:
    """Generate simple text report as fallback"""
    report = []
    report.append("PAIPERSUM LEGAL ANALYSIS REPORT")
    report.append("=" * 50)
    report.append("")
    
    # Risk assessment
    risk_score = analysis_data.get('risk_score', 0)
    confidence = analysis_data.get('confidence', 0.0)
    
    report.append(f"Risk Score: {risk_score}%")
    report.append(f"Confidence: {confidence:.1%}")
    report.append("")
    
    # Clauses
    clauses = analysis_data.get('clauses', [])
    if clauses:
        report.append("IDENTIFIED LEGAL CLAUSES:")
        report.append("-" * 30)
        for i, clause in enumerate(clauses, 1):
            report.append(f"{i}. {clause.get('title', 'Unknown')}")
            report.append(f"   {clause.get('summary', 'No summary')}")
            if clause.get('citation'):
                report.append(f"   Source: {clause.get('citation', '')[:100]}...")
            report.append("")
    else:
        report.append("No significant legal clauses identified.")
        report.append("")
    
    # Disclaimer
    report.append("LEGAL DISCLAIMER:")
    report.append("-" * 20)
    report.append("This analysis is for informational purposes only and does not constitute legal advice.")
    report.append("Consult with a qualified attorney for legal decisions.")
    
    return "\n".join(report)